import { existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import os from "node:os"
import path from "node:path"
import { VENDOR_PROVIDER_NAMES } from "@claxedo/agent-runtime-contract"
import { asRecord, asString } from "@claxedo/helpers/guards"
import { assertTemporaryHome } from "../../../script/test-home/temporary-home.mjs"
import type { ProviderModel } from "../src/contract"
import { engineProviderBinding } from "../src/transports/opencode-sdk/credentials"
import { createOpenCodeRuntime } from "../src/transports/opencode-sdk/runtime"
import { WorkspaceScope } from "../src/transports/opencode-sdk/scope"

const packageRoot = path.resolve(import.meta.dirname, "..")
const output = path.join(packageRoot, "src/transports/opencode-sdk/bundled-models.generated.ts")
const vendors = Object.keys(VENDOR_PROVIDER_NAMES)

function engineVersion(): string {
  const manifest = path.join(packageRoot, "node_modules/@opencode-ai/sdk/package.json")
  const version = asString(asRecord(JSON.parse(readFileSync(manifest, "utf8")))?.version)
  if (!version) throw new Error(`${manifest} names no version`)
  return version
}

async function engineModels(root: string): Promise<readonly ProviderModel[]> {
  const directory = path.join(root, "work")
  mkdirSync(directory)
  const runtime = createOpenCodeRuntime({ databasePath: path.join(root, "opencode.db"), persistEvents: false })
  try {
    const providers = Object.fromEntries(vendors.map((id) => [id, { baseUrl: "https://unused.invalid/v1", placeholder: "bundled-catalog", authMode: "api-key" as const }]))
    await runtime.bindProviders(engineProviderBinding({ credentials: { machineLoginAllowed: false, providers, secrets: {} } }))
    return await runtime.catalog.models(WorkspaceScope.authorize({ workspaceID: "bundled-catalog", directory }))
  } finally {
    await runtime.close()
  }
}

function render(version: string, models: readonly ProviderModel[]): string {
  const row = (model: ProviderModel) => `    ${JSON.stringify([model.id, model.name ?? model.id, model.variants ?? []])},`
  const providers = vendors.map((id) => {
    const rows = models.filter((model) => model.providerID === id).map(row)
    return [`  ${JSON.stringify(id)}: [`, ...rows, "  ],"].join("\n")
  })
  return [
    `// @generated by scripts/generate-opencode-models.ts from @opencode-ai/sdk ${version}; run \`bun run generate:opencode-models\` after changing the engine.`,
    `export const BUNDLED_ENGINE_VERSION = ${JSON.stringify(version)}`,
    "",
    "type BundledModel = readonly [id: string, name: string, variants: readonly string[]]",
    "",
    "export const BUNDLED_MODELS: Readonly<Record<string, readonly BundledModel[]>> = {",
    ...providers,
    "}",
    "",
  ].join("\n")
}

assertTemporaryHome()
const root = mkdtempSync(path.join(os.tmpdir(), "opencode-bundled-models-"))
try {
  const next = render(engineVersion(), await engineModels(root))
  if (!existsSync(output) || readFileSync(output, "utf8") !== next) writeFileSync(output, next)
} finally {
  rmSync(root, { recursive: true, force: true })
}

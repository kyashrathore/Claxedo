const codexOutput = path.join(packageRoot, "src/transports/codex-app-server/bundled-models.generated.ts")
const UNREACHABLE = "https://unused.invalid"
const ACCOUNT_ENV = ["ANTHROPIC_API_KEY", "ANTHROPIC_AUTH_TOKEN", "CLAUDE_CODE_OAUTH_TOKEN", "ANTHROPIC_BASE_URL", "OPENAI_API_KEY", "CODEX_API_KEY", "OPENAI_BASE_URL"]
const CLAUDE_FORMS: Record<ClaudeAccountForm, Record<string, string>> = {
  api: { ANTHROPIC_API_KEY: "sk-ant-api-bundled-catalog" },
  plan: { CLAUDE_CODE_OAUTH_TOKEN: "sk-ant-oat01-bundled-catalog" },
}

function installedVersion(name: string): string {
  const manifest = path.join(packageRoot, "node_modules", name, "package.json")
  const version = asString(asRecord(JSON.parse(readFileSync(manifest, "utf8")))?.version)
  if (!version) throw new Error(`${manifest} names no version`)
  return version
}

function accountFreeEnv(extra: Record<string, string>): Record<string, string> {
  const env = Object.fromEntries(Object.entries(process.env).filter((entry): entry is [string, string] => entry[1] !== undefined && !ACCOUNT_ENV.includes(entry[0])))
  return { ...env, ...extra }
}

async function claudeModels(form: ClaudeAccountForm): Promise<ModelInfo[]> {
  const abort = new AbortController()
  const probe = query({ prompt: { async *[Symbol.asyncIterator]() {
    await new Promise<void>((resolve) => abort.signal.addEventListener("abort", () => resolve(), { once: true }))
  } }, options: { cwd: process.env.HOME, abortController: abort, env: accountFreeEnv({ ...CLAUDE_FORMS[form], ANTHROPIC_BASE_URL: UNREACHABLE }) } })
  try {
    return await probe.supportedModels()
  } finally {
    abort.abort()
    probe.close()
  }
}

function claudeRow(model: ModelInfo): ModelInfo {
  return {
    value: model.value, displayName: model.displayName, description: model.description,
    ...(model.resolvedModel ? { resolvedModel: model.resolvedModel } : {}),
    ...(model.supportsEffort !== undefined ? { supportsEffort: model.supportsEffort } : {}),
    ...(model.supportedEffortLevels ? { supportedEffortLevels: model.supportedEffortLevels } : {}),
  }
}

function renderClaude(version: string, forms: Record<ClaudeAccountForm, readonly ModelInfo[]>): string {
  const rows = (form: ClaudeAccountForm) => [`  ${form}: [`, ...forms[form].map((model) => `    ${JSON.stringify(claudeRow(model))},`), "  ],"]
  return [
    `// @generated by scripts/generate-native-models.ts from @anthropic-ai/claude-agent-sdk ${version}; run \`bun run generate:native-models\` after changing the SDK.`,
    `import type { ModelInfo } from "@anthropic-ai/claude-agent-sdk"`,
    "",
    `export const CLAUDE_BUNDLED_SDK_VERSION = ${JSON.stringify(version)}`,
    "",
    `export const CLAUDE_BUNDLED_MODELS: Readonly<Record<"api" | "plan", readonly ModelInfo[]>> = {`,
    ...rows("api"),
    ...rows("plan"),
    "}",
    "",
  ].join("\n")
}

function codexConnection(binary: string): { connection: CodexConnection; close(): void } {
  const child = spawn(process.execPath, [binary, "app-server"], { stdio: ["pipe", "pipe", "inherit"],
    env: accountFreeEnv({ OPENAI_BASE_URL: `${UNREACHABLE}/v1` }) })
  const pending = new Map<number, (message: RpcMessage) => void>()
  const failures: ((error: Error) => void)[] = []
  readline.createInterface({ input: child.stdout }).on("line", (line) => {
    const message = asRecord(JSON.parse(line)) as RpcMessage | undefined
    if (typeof message?.id === "number") pending.get(message.id)?.(message)
  })
  child.on("exit", (code) => failures.forEach((listener) => listener(new Error(`codex app-server exited with ${code}`))))
  let next = 0
  const connection: CodexConnection = {
    get alive() { return child.exitCode === null },
    request: (method, params) => new Promise((resolve, reject) => {
      const id = ++next
      pending.set(id, (message) => {
        pending.delete(id)
        if (message.error) reject(new Error(`${method}: ${message.error.message}`))
        else resolve(message.result)
      })
      child.stdin.write(`${JSON.stringify({ id, method, ...(params === undefined ? {} : { params }) })}\n`)
    }),
    onMessage: () => () => {},
    onFailure: (listener) => {
      failures.push(listener)
      return () => failures.splice(failures.indexOf(listener), 1)
    },
  }
  return { connection, close: () => child.kill() }
}

async function codexModels(): Promise<CodexModel[]> {
  const { connection, close } = codexConnection(path.join(packageRoot, "node_modules/@openai/codex/bin/codex.js"))
  try {
    await connection.request("initialize", { clientInfo: { name: "claxedo-bundled-catalog", version: "0" } })
    await connection.request("account/login/start", { type: "apiKey", apiKey: "sk-bundled-catalog" })
    return await readCodexModels(connection)
  } finally {
    close()
  }
}

function renderCodex(version: string, models: readonly CodexModel[]): string {
  return [
    `// @generated by scripts/generate-native-models.ts from @openai/codex ${version}; run \`bun run generate:native-models\` after changing Codex.`,
    `import type { CodexModel } from "./models"`,
    "",
    `export const CODEX_BUNDLED_VERSION = ${JSON.stringify(version)}`,
    "",
    "export const CODEX_BUNDLED_MODELS: readonly CodexModel[] = [",
    ...models.map((model) => `  ${JSON.stringify(model)},`),
    "]",
    "",
  ].join("\n")
}

function writeIfChanged(file: string, next: string) {
  if (!existsSync(file) || readFileSync(file, "utf8") !== next) writeFileSync(file, next)
}

assertTemporaryHome()
writeIfChanged(claudeOutput, renderClaude(installedVersion("@anthropic-ai/claude-agent-sdk"), { api: await claudeModels("api"), plan: await claudeModels("plan") }))
writeIfChanged(codexOutput, renderCodex(installedVersion("@openai/codex"), await codexModels()))

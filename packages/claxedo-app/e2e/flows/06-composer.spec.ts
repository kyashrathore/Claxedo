test("06 a closed tooltip holds no tooltip machinery until the pointer reaches it, and then opens on hover as before", async ({ stack, api, app, isMobile }) => {
  test.skip(isMobile, "hover tooltips are a pointer device's")
  const workspace = await stack.daemon.makeWorkspace("tooltip")
  const session = await api.createSession(workspace.directory, { title: "Tooltip", harness: SCRIPTED_ACP_HARNESS })
  await app.goto(`${stack.url}${sessionRoute(workspace.id, session.id)}`)
  const chip = app.locator('[data-action="prompt-permission-mode"]').filter({ visible: true })
  await expect(chip).toBeVisible()
  const trigger = app.locator('[data-component="tooltip-v2-trigger"]').filter({ has: chip })
  const cdp = await app.context().newCDPSession(app)
  const listeners = async () => {
    await trigger.evaluate((element) => ((window as unknown as { __tooltipTrigger: Element }).__tooltipTrigger = element))
    const { result } = await cdp.send("Runtime.evaluate", { expression: "window.__tooltipTrigger" })
    const { listeners: attached } = await cdp.send("DOMDebugger.getEventListeners", { objectId: result.objectId! })
    return [...new Set(attached.map((listener) => listener.type))].sort()
  }

  const closed = await listeners()
  expect(closed).not.toContain("focus")
  expect(closed).not.toContain("blur")
  expect(await trigger.getAttribute("data-closed")).toBe("")
  expect(await trigger.getAttribute("aria-describedby")).toBeNull()

  await chip.hover()
  await expect(app.getByRole("tooltip")).toBeVisible()
  expect(await listeners()).toEqual(expect.arrayContaining(["blur", "focus"]))
  await app.mouse.move(0, 0)
  await expect(app.getByRole("tooltip")).toHaveCount(0)
})


test("06 a menu that has never opened holds no menu machinery, and its first press opens it", async ({ stack, api, app, isMobile }) => {
  test.skip(isMobile, "the composer toolbar's add menu is checked at desktop width")
  const workspace = await stack.daemon.makeWorkspace("menu-closed")
  const session = await api.createSession(workspace.directory, { title: "Menu", harness: SCRIPTED_ACP_HARNESS })
  await app.goto(`${stack.url}${sessionRoute(workspace.id, session.id)}`)
  const trigger = app.locator('[data-action="prompt-add"]').filter({ visible: true })
  await expect(trigger).toBeEnabled()
  const cdp = await app.context().newCDPSession(app)
  await trigger.evaluate((element) => ((window as unknown as { __menuTrigger: Element }).__menuTrigger = element))
  const { result } = await cdp.send("Runtime.evaluate", { expression: "window.__menuTrigger" })
  const { listeners } = await cdp.send("DOMDebugger.getEventListeners", { objectId: result.objectId! })
  expect(listeners.map((listener) => listener.type)).not.toContain("focus")
  await expect(trigger).toHaveAttribute("aria-haspopup", "true")
  await expect(trigger).toHaveAttribute("aria-expanded", "false")
  await expect(trigger).toHaveAttribute("data-closed", "")
  await expect(trigger).toHaveAttribute("id", /-trigger$/)

  await trigger.click()
  await expect(app.getByRole("menu")).toBeVisible()
  await expect(trigger).toHaveAttribute("aria-expanded", "true")
  await expect(app.getByRole("menu")).toHaveAttribute("aria-labelledby", (await trigger.getAttribute("id"))!)
  await app.keyboard.press("Escape")
  await expect(app.getByRole("menu")).toHaveCount(0)
})

test("06 the first key on a never-opened menu trigger opens the menu on its first item, and typing moves to a match", async ({ stack, api, app, isMobile }) => {
  test.skip(isMobile, "the composer toolbar's add menu is checked at desktop width")
  const workspace = await stack.daemon.makeWorkspace("menu-keys")
  const session = await api.createSession(workspace.directory, { title: "Menu keys", harness: SCRIPTED_ACP_HARNESS })
  await app.goto(`${stack.url}${sessionRoute(workspace.id, session.id)}`)
  const trigger = app.locator('[data-action="prompt-add"]').filter({ visible: true })
  await expect(trigger).toBeEnabled()
  await trigger.focus()

  await app.keyboard.press("ArrowDown")
  const menu = app.getByRole("menu")
  await expect(menu).toBeVisible()
  await expect(menu.getByRole("menuitem").first()).toBeFocused()
  const items = menu.locator('[role="menuitem"]:not([aria-disabled="true"])')
  const labels = (await items.allTextContents()).map((label) => label.trim())
  const target = labels.findIndex((label, index) => index > 0 && labels.filter((other) => other[0]?.toLowerCase() === label[0]?.toLowerCase()).length === 1)
  expect(target).toBeGreaterThan(0)
  await app.keyboard.press(labels[target][0].toLowerCase())
  await expect(items.nth(target)).toBeFocused()
})
